#!/usr/bin/env python3
"""Write MANIFEST.md: environment, parameters, public test-key ids, artifact hashes, the external inputs of the
actual-C2PA run, and the SHA-256 of every file listed in PRODUCT_ALLOWLIST.txt. Run after run_experiment.py."""

import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ALLOWLIST = "PRODUCT_ALLOWLIST.txt"


def product_files():
    """Paths listed in PRODUCT_ALLOWLIST.txt, in order. Blank lines and lines starting with '#' are ignored.
    Exits with an error if a listed file is missing."""
    with open(os.path.join(HERE, ALLOWLIST)) as f:
        paths = [line.strip() for line in f if line.strip() and not line.lstrip().startswith("#")]
    missing = [p for p in paths if not os.path.isfile(os.path.join(HERE, p))]
    if missing:
        sys.exit("files listed in %s are missing: %s" % (ALLOWLIST, ", ".join(missing)))
    return paths


def sha(path):
    with open(os.path.join(HERE, path), "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def main():
    with open(os.path.join(HERE, "results", "results.json")) as f:
        r = json.load(f)
    lines = ["# Technical manifest", "",
             "Generated by `make_manifest.py` from `results/results.json`. Re-running `run_experiment.py` on the same "
             "tool versions should reproduce the artifact hashes below: images, watermark patterns and test keys are all "
             "deterministic, and Ed25519 signatures are deterministic for a given key.", "",
             "## Environment of the recorded run", ""]
    for k, v in r["environment"].items():
        lines.append("- **%s:** `%s`" % (k, json.dumps(v) if isinstance(v, dict) else v))
    lines += ["", "## Parameters", ""]
    for k, v in r["parameters"].items():
        lines.append("- %s: `%s`" % (k, v))
    lines += ["", "## Test keys (public identifiers only; private keys are derived from public labels and are NOT secret)", ""]
    for k, v in r["test_key_ids"].items():
        lines.append("- %s: `%s`" % (k, v))
    lines += ["", "## Generated image artifacts (written to results/artifacts/, not committed)", "",
              "| File | File SHA-256 | Pixel SHA-256 |", "|---|---|---|"]
    for name, h in sorted(r["artifact_hashes"].items()):
        lines.append("| %s | `%s` | `%s` |" % (name, h["file_sha256"], h["pixel_sha256"]))
    actual = os.path.join(HERE, "results", "actual_c2pa", "actual_c2pa_results.json")
    if os.path.exists(actual):
        with open(actual) as f:
            a = json.load(f)
        lines += ["", "## External inputs for the actual-C2PA run (not committed)", "",
                  "- Tool: `%s` %s, release %s" % (a["tool"]["name"], a["tool"]["version"], a["tool"]["release_url"]),
                  "- Release asset: `%s`, %d bytes, SHA-256 `%s` (matches GitHub's recorded digest)" % (
                      a["tool"]["asset"], a["tool"]["asset_size_bytes"], a["tool"]["asset_sha256_recorded_by_github"]),
                  "- Extracted binary SHA-256: `%s`; reported version: `%s`" % (
                      a["environment"]["tool_binary_sha256"], a["environment"]["c2patool_version_reported"]),
                  "- Licence: %s; signing: %s" % (a["tool"]["license"], a["tool"]["signing"]),
                  "", "| Sample | Source | SHA-256 | Git blob matches GitHub |", "|---|---|---|---|"]
        for e in a["official_samples"]:
            lines.append("| %s | %s | `%s` | %s |" % (e["file"], e["source"], e["sha256"], e.get("git_blob_sha_matches_github", "n/a (bundled)")))
    lines += ["", "## Product files (listed in %s; SHA-256 at the time this manifest was generated)" % ALLOWLIST, "",
              "| File | SHA-256 |", "|---|---|"]
    for p in product_files():
        if p != "MANIFEST.md":
            lines.append("| %s | `%s` |" % (p, sha(p)))
    lines.append("")
    lines.append("MANIFEST.md itself is not listed because it cannot contain its own hash.")
    with open(os.path.join(HERE, "MANIFEST.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote MANIFEST.md")


if __name__ == "__main__":
    main()
