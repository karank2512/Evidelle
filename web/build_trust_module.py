"""Regenerate trust-anchors.js from the pinned trust-list PEM files.

Reads web/trust/C2PA-TRUST-LIST.pem and web/trust/C2PA-TSA-TRUST-LIST.pem and writes
web/trust-anchors.js, recording each file's SHA-256, its source and the date it was fetched.
The fetch date is read from the file's modification time by default; override it with
--fetched YYYY-MM-DD when the PEMs were downloaded on another day.

    python3 web/build_trust_module.py [--fetched YYYY-MM-DD]

The PEMs are the official C2PA conformance trust lists from
https://github.com/c2pa-org/conformance-public/tree/main/trust-list and are not edited.
"""

import argparse
import datetime
import hashlib
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
PEMS = {
    "MANIFEST_TRUST_LIST": ("trust/C2PA-TRUST-LIST.pem",
                            "https://raw.githubusercontent.com/c2pa-org/conformance-public/main/trust-list/C2PA-TRUST-LIST.pem"),
    "TSA_TRUST_LIST": ("trust/C2PA-TSA-TRUST-LIST.pem",
                       "https://raw.githubusercontent.com/c2pa-org/conformance-public/main/trust-list/C2PA-TSA-TRUST-LIST.pem"),
    "INTERIM_TRUST_LIST": ("trust/C2PA-INTERIM-TRUST-LIST.pem",
                           "https://contentcredentials.org/trust/anchors.pem"),
}
TEXTS = {
    "INTERIM_EKU_STORE": "trust/c2pa-interim-eku-store.cfg",
}
TEST_CERT_MARKERS = ("C2PA Test", "FOR TESTING")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--fetched", default=None,
                    help="Date the PEMs were downloaded (YYYY-MM-DD). Default: file modification date.")
    args = ap.parse_args()
    entries = {}
    for name, (rel, url) in PEMS.items():
        data = (HERE / rel).read_bytes()
        fetched = args.fetched or datetime.date.fromtimestamp((HERE / rel).stat().st_mtime).isoformat()
        entries[name] = {
            "pem": data.decode("ascii"),
            "source": url,
            "sha256": hashlib.sha256(data).hexdigest(),
            "fetched": fetched,
            "certificates": data.count(b"-----BEGIN CERTIFICATE-----"),
        }
    out = [
        "// Generated by web/build_trust_module.py from the pinned PEM files in web/trust/.\n",
        "// Do not edit by hand; run the generator again after updating the PEMs.\n",
        "// MANIFEST_TRUST_LIST and TSA_TRUST_LIST are the official C2PA conformance lists\n",
        "// (the same lists the Adobe Content Authenticity Inspect tool uses).\n",
        "// INTERIM_TRUST_LIST is the frozen CAI interim list the C2PA Verify site uses; its own\n",
        "// header says validators should distinguish credentials signed under it from those\n",
        "// signed under the official list. INTERIM_EKU_STORE is the EKU store c2patool fetched\n",
        "// for the interim list. Everything is fetched once and pinned here; nothing is fetched\n",
        "// at check time.\n",
        "export const TRUST = " + json.dumps(entries, indent=2) + ";\n",
        "export const TRUST_TEXTS = " + json.dumps(
            {k: (HERE / rel).read_text() for k, rel in TEXTS.items()}, indent=2) + ";\n",
        "// Substrings that mark the public C2PA TEST signing credentials. A signer whose\n",
        "// certificate declares these is not on any production trust list by definition;\n",
        "// its private key is published inside the c2patool release.\n",
        "export const TEST_CERT_MARKERS = " + json.dumps(TEST_CERT_MARKERS) + ";\n",
        "export default TRUST;\n",
    ]
    (HERE / "trust-anchors.js").write_text("".join(out))
    for name, e in entries.items():
        print(f"{name}: {e['certificates']} certificates, sha256 {e['sha256'][:16]}..., fetched {e['fetched']}")


if __name__ == "__main__":
    main()
